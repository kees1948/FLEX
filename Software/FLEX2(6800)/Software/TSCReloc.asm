         FCB 4
         FCC "PRESENT PROGRAM:"
         FCB 4
BEGADR   FCC "BEGIN ADDRESS? "
         FCB 4
ENDADR   FCC "  END ADDRESS? "
         FCB 4
NEWBG    FCC "      MOVE TO? "
         FCB 4
TAPSTR   FCC "LOAD FROM TAPE? "
         FCB 4
LOADED   FCC "...LOAD COMPLETED."
         FCB 4
FIXRFS   FCC "FIX REFERENCES? "
         FCB 4
DRCTBK   FCC "DATA BLOCKS? "
         FCB 4
CHANGE   FCC "ALTER RANGE? "
         FCB 4
FINE     FCC "RELOCATION COMPLETED !!!"
         FCB 4
FXFDBS   FCC "FIX FDB"
         FCB $27,$53,$3F,$20,4
